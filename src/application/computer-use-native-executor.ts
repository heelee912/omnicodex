import { randomUUID } from "node:crypto";
import { access } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import type { NativeToolExecutor } from "./native-tool-catalog.js";

export type ComputerUseMethod =
  | "list_apps"
  | "list_windows"
  | "get_window"
  | "launch_app"
  | "get_window_state"
  | "click"
  | "press_key"
  | "type_text"
  | "scroll"
  | "set_value"
  | "drag"
  | "perform_secondary_action"
  | "activate_window";

export interface ComputerUseNativeExecutorOptions {
  /** Test/development override. Production uses the bundled package name. */
  readonly skyEntryPath?: string;
  /** Maximum immutable observations retained across all callers. */
  readonly maxObservationFrames?: number;
  /** Maximum time a state-derived input can reuse an observation. */
  readonly observationFrameTtlMs?: number;
  /** Test-only clock override. */
  readonly now?: () => number;
}

interface ComputerUseWindow {
  readonly app: string;
  readonly id: number;
  readonly title?: string;
}

interface ScreenshotGeometry {
  readonly id: string;
  readonly height?: number;
  readonly originX?: number;
  readonly originY?: number;
  readonly width?: number;
  readonly zIndex?: number;
}

interface ObservationFrame {
  readonly callerKey: string;
  readonly frameId: string;
  readonly generation: number;
  readonly helperGeneration: string;
  readonly issuedAt: number;
  readonly expiresAt?: number;
  readonly operationId?: string;
  readonly turnId?: string;
  readonly window: ComputerUseWindow;
  readonly windowKey: string;
  readonly screenshots: readonly ScreenshotGeometry[];
  readonly hasAccessibility: boolean;
}

interface PreparedFrame {
  readonly frame: ObservationFrame;
}

interface ParsedComputerUseResult {
  readonly value: unknown;
  readonly helperGeneration?: string;
}

/** An explicit failure returned in this call's correlated native response. */
export class ComputerUseNativeResponseError extends Error {}

/** Executes the installed first-party @oai/sky API without a model turn. */
export class ComputerUseNativeExecutor {
  readonly #nativeTools: Pick<NativeToolExecutor, "callInContext">;
  readonly #options: ComputerUseNativeExecutorOptions;
  readonly #maxObservationFrames: number | undefined;
  readonly #observationFrameTtlMs: number | undefined;
  readonly #now: () => number;
  readonly #frames: ObservationFrame[] = [];
  #frameGeneration = 0;
  #skyModuleSpecifier: string | undefined;

  constructor(
    nativeTools: Pick<NativeToolExecutor, "callInContext">,
    options: ComputerUseNativeExecutorOptions = {},
  ) {
    this.#nativeTools = nativeTools;
    this.#options = options;
    this.#maxObservationFrames = optionalPositiveInteger(
      options.maxObservationFrames,
      "maxObservationFrames",
    );
    this.#observationFrameTtlMs = optionalPositiveInteger(
      options.observationFrameTtlMs,
      "observationFrameTtlMs",
    );
    this.#now = options.now ?? Date.now;
  }

  async call(
    method: ComputerUseMethod,
    argumentsValue: unknown,
    contextThreadId?: string,
    contextTurnId?: string,
    signal?: AbortSignal,
    operationId?: string,
    callerSessionId?: string,
  ): Promise<unknown> {
    if (!computerUseMethods.has(method)) throw new Error(`Unknown Computer Use method: ${method}`);
    const args = isObject(argumentsValue) ? argumentsValue : {};
    if (method === "get_window_state" || verifiedWindowActionMethods.has(method)) {
      requireCallerKey(contextThreadId, contextTurnId, callerSessionId);
    }
    const preparedFrame = this.#prepareFrame(
      method,
      args,
      contextThreadId,
      contextTurnId,
      callerSessionId,
    );
    // Sky's state-derived inputs must address the native observation context,
    // not a new implicit turn generated by the downstream executor per call.
    const nativeTurnId = contextTurnId ?? preparedFrame?.frame.turnId ?? randomUUID();
    const skyModuleSpecifier = await this.#resolveSkyModuleSpecifier();
    const marker = `OMNICODEX_SKY_${randomUUID()}:`;
    const helperGenerationCandidate = randomUUID();
    const noInput = method === "list_apps" || method === "list_windows";
    const verifyWindowState = verifiedWindowActionMethods.has(method);
    const actionWindowKey = verifyWindowState
      ? canonicalWindowKey(requireWindow(args.window))
      : undefined;
    const code = [
      "try {",
      "  if (!globalThis.__omnicodexSky) {",
      `    const { sky: __omniImportedSky } = await import(${JSON.stringify(skyModuleSpecifier)});`,
      "    globalThis.__omnicodexSky = __omniImportedSky;",
      "  }",
      `  if (!globalThis.__omnicodexSkyGeneration) globalThis.__omnicodexSkyGeneration = ${JSON.stringify(helperGenerationCandidate)};`,
      "  const __omniSky = globalThis.__omnicodexSky;",
      `  const __omniInput = ${jsonLiteral(args)};`,
      ...(preparedFrame === undefined
        ? []
        : [
            `  if (globalThis.__omnicodexSkyGeneration !== ${JSON.stringify(preparedFrame.frame.helperGeneration)}) {`,
            "    throw new Error('Computer Use observation belongs to a stale helper generation; reobserve before acting');",
            "  }",
          ]),
      `  const __omniResult = await __omniSky[${JSON.stringify(method)}](${noInput ? "" : "__omniInput"});`,
      `  console.log(${JSON.stringify(marker)} + JSON.stringify({ ok: true, value: __omniResult ?? null, helperGeneration: globalThis.__omnicodexSkyGeneration }));`,
      "} catch (__omniError) {",
      "  const __omniSeen = new WeakSet();",
      "  const __omniSafeErrorValue = (__omniValue) => {",
      "    if (__omniValue === null || typeof __omniValue === 'string' || typeof __omniValue === 'boolean') return __omniValue;",
      "    if (typeof __omniValue === 'number') return Number.isFinite(__omniValue) ? __omniValue : String(__omniValue);",
      "    if (typeof __omniValue === 'bigint') return __omniValue.toString();",
      "    if (__omniValue === undefined) return null;",
      "    if (typeof __omniValue !== 'object') return String(__omniValue);",
      "    if (__omniSeen.has(__omniValue)) return '[Circular]';",
      "    __omniSeen.add(__omniValue);",
      "    if (Array.isArray(__omniValue)) return __omniValue.map(__omniSafeErrorValue);",
      "    const __omniOutput = {};",
      "    let __omniObjectTag = '[object Object]';",
      "    try { __omniObjectTag = Object.prototype.toString.call(__omniValue); } catch {}",
      "    let __omniConstructorName;",
      "    try { __omniConstructorName = typeof __omniValue.constructor?.name === 'string' ? __omniValue.constructor.name : undefined; } catch {}",
      "    const __omniReadInherited = (__omniKey) => {",
      "      try { return Reflect.get(__omniValue, __omniKey); } catch { return undefined; }",
      "    };",
      "    const __omniName = __omniReadInherited('name');",
      "    const __omniMessage = __omniReadInherited('message');",
      "    const __omniStack = __omniReadInherited('stack');",
      "    if (typeof __omniName === 'string' && __omniName.length > 0) __omniOutput.name = __omniName;",
      "    else if (__omniConstructorName && __omniConstructorName !== 'Object') __omniOutput.name = __omniConstructorName;",
      "    if (typeof __omniMessage === 'string' && __omniMessage.length > 0) __omniOutput.message = __omniMessage;",
      "    if (typeof __omniStack === 'string' && __omniStack.length > 0) __omniOutput.stack = __omniStack;",
      "    __omniOutput.objectTag = __omniObjectTag;",
      "    if (__omniConstructorName) __omniOutput.constructorName = __omniConstructorName;",
      "    for (const __omniKey of Object.getOwnPropertyNames(__omniValue)) {",
      "      if (__omniKey === 'name' || __omniKey === 'message' || __omniKey === 'stack') continue;",
      "      try { __omniOutput[__omniKey] = __omniSafeErrorValue(__omniValue[__omniKey]); }",
      "      catch (__omniReadError) { __omniOutput[__omniKey] = { inaccessible: true, reason: String(__omniReadError) }; }",
      "    }",
      "    for (const __omniSymbol of Object.getOwnPropertySymbols(__omniValue)) {",
      // biome-ignore lint/suspicious/noTemplateCurlyInString: Interpolation belongs to the emitted native script.
      "      const __omniSymbolKey = `[${String(__omniSymbol)}]`;",
      "      try { __omniOutput[__omniSymbolKey] = __omniSafeErrorValue(__omniValue[__omniSymbol]); }",
      "      catch (__omniReadError) { __omniOutput[__omniSymbolKey] = { inaccessible: true, reason: String(__omniReadError) }; }",
      "    }",
      "    if (typeof __omniOutput.message !== 'string') {",
      "      let __omniRendered;",
      "      try { __omniRendered = String(__omniValue); } catch {}",
      "      const __omniIdentity = [__omniConstructorName, __omniObjectTag].filter(Boolean).join(' ');",
      // biome-ignore lint/suspicious/noTemplateCurlyInString: Interpolation belongs to the emitted native script.
      "      __omniOutput.message = __omniRendered && __omniRendered !== __omniObjectTag ? __omniRendered : `Computer Use runtime rejected with ${__omniIdentity || 'an opaque object'}`;",
      "    }",
      "    return __omniOutput;",
      "  };",
      `  console.log(${JSON.stringify(marker)} + JSON.stringify({ ok: false, error: __omniSafeErrorValue(__omniError) }));`,
      "}",
    ].join("\n");
    const parsed = await (async () => {
      try {
        const result = await this.#nativeTools.callInContext(
          "node_repl",
          "js",
          {
            code,
            title: `Computer Use: ${method}`,
          },
          contextThreadId,
          undefined,
          nativeTurnId,
          signal,
          callerSessionId,
        );
        return parseMarker(result, marker);
      } catch (error) {
        // Once a native input is dispatched its outcome can be ambiguous. Any
        // observation of the mutated physical window is stale, but unrelated
        // callers are not invalidated by read-only observations.
        if (actionWindowKey !== undefined) this.#removeFramesForWindow(actionWindowKey);
        throw error;
      }
    })();
    if (method === "get_window_state") {
      this.#recordObservation(
        parsed.value,
        parsed.helperGeneration,
        contextThreadId,
        nativeTurnId,
        operationId,
        callerSessionId,
      );
    } else if (verifyWindowState) {
      if (actionWindowKey !== undefined) this.#removeFramesForWindow(actionWindowKey);
    }
    return parsed.value;
  }

  #prepareFrame(
    method: ComputerUseMethod,
    args: Record<string, unknown>,
    contextThreadId: string | undefined,
    contextTurnId: string | undefined,
    callerSessionId: string | undefined,
  ): PreparedFrame | undefined {
    if (!verifiedWindowActionMethods.has(method)) return undefined;
    const window = requireWindow(args.window);
    const requirement = frameRequirement(method, args);
    let selected: ObservationFrame | undefined;
    if (requirement !== "none") {
      const callerKey = requireCallerKey(contextThreadId, contextTurnId, callerSessionId);
      selected = this.#selectFrame(callerKey, window, requirement, args.screenshotId);
    }

    // Claim the physical window before the first await so two callers cannot
    // act from concurrent point-in-time observations. This is a real input
    // boundary; read-only observations remain independent until this point.
    this.#removeFramesForWindow(canonicalWindowKey(window));
    this.#pruneFrames();
    if (selected === undefined) return undefined;
    return {
      frame: selected,
    };
  }

  #selectFrame(
    callerKey: string,
    window: ComputerUseWindow,
    requirement: "screenshot" | "accessibility" | "state",
    screenshotIdValue: unknown,
  ): ObservationFrame {
    const now = this.#now();
    const windowKey = canonicalWindowKey(window);
    const screenshotId = typeof screenshotIdValue === "string" ? screenshotIdValue : undefined;
    const candidates = this.#frames
      .filter((frame) => frame.windowKey === windowKey)
      .sort((left, right) => right.issuedAt - left.issuedAt || right.generation - left.generation);
    const tokenMatches = candidates.filter((frame) =>
      screenshotId !== undefined
        ? frame.screenshots.some((screenshot) => screenshot.id === screenshotId)
        : requirement !== "screenshot" || frame.screenshots.length > 0,
    );
    const callerFrame = tokenMatches.find((frame) => frame.callerKey === callerKey);
    if (callerFrame === undefined) {
      if (tokenMatches.length > 0) {
        throw new Error(
          "Computer Use observation was issued to another caller; capture a new state in this caller before acting",
        );
      }
      throw new Error(
        requirement === "screenshot"
          ? "Computer Use screenshotId is stale or unknown; capture a new window state before acting"
          : "Computer Use has no current observation for this caller and window; capture a new state before acting",
      );
    }
    if (callerFrame.expiresAt !== undefined && callerFrame.expiresAt <= now) {
      this.#removeFrame(callerFrame.frameId);
      throw new Error("Computer Use observation expired; capture a new window state before acting");
    }
    if (requirement === "accessibility" && !callerFrame.hasAccessibility) {
      throw new Error(
        "Computer Use input requires a current accessibility observation for this caller and window",
      );
    }
    return callerFrame;
  }

  #recordObservation(
    value: unknown,
    helperGeneration: string | undefined,
    contextThreadId: string | undefined,
    contextTurnId: string | undefined,
    operationId: string | undefined,
    callerSessionId: string | undefined,
  ): void {
    const callerKey = requireCallerKey(contextThreadId, contextTurnId, callerSessionId);
    if (typeof helperGeneration !== "string" || helperGeneration.length === 0) {
      throw new Error("Computer Use state is missing its helper-generation binding");
    }
    if (!isObject(value)) throw new Error("Computer Use returned an invalid window state");
    const window = requireWindow(value.window);
    const windowKey = canonicalWindowKey(window);
    const now = this.#now();
    this.#frameGeneration += 1;
    const generation = this.#frameGeneration;
    const screenshots = Object.freeze(
      (Array.isArray(value.screenshots) ? value.screenshots : [])
        .filter(isObject)
        .map(screenshotGeometry)
        .filter((candidate): candidate is ScreenshotGeometry => candidate !== undefined),
    );
    const frame: ObservationFrame = Object.freeze({
      callerKey,
      frameId: randomUUID(),
      generation,
      helperGeneration,
      issuedAt: now,
      ...(this.#observationFrameTtlMs === undefined
        ? {}
        : { expiresAt: observationExpiry(now, this.#observationFrameTtlMs) }),
      ...(operationId === undefined ? {} : { operationId }),
      ...(contextTurnId === undefined ? {} : { turnId: contextTurnId }),
      window: Object.freeze({ ...window }),
      windowKey,
      screenshots,
      hasAccessibility: value.accessibility !== null && value.accessibility !== undefined,
    });

    // A read-only observation advances only this caller's view. Other callers
    // retain their independently issued frame until a physical input occurs.
    this.#removeFramesForCallerWindow(callerKey, windowKey);
    this.#frames.push(frame);
    this.#pruneFrames();
    if (this.#maxObservationFrames !== undefined) {
      while (this.#frames.length > this.#maxObservationFrames) this.#frames.shift();
    }
  }

  #removeFrame(frameId: string): void {
    const index = this.#frames.findIndex((frame) => frame.frameId === frameId);
    if (index >= 0) this.#frames.splice(index, 1);
  }

  #removeFramesForWindow(windowKey: string): void {
    for (let index = this.#frames.length - 1; index >= 0; index -= 1) {
      if (this.#frames[index]?.windowKey === windowKey) this.#frames.splice(index, 1);
    }
  }

  #removeFramesForCallerWindow(callerKey: string, windowKey: string): void {
    for (let index = this.#frames.length - 1; index >= 0; index -= 1) {
      const frame = this.#frames[index];
      if (frame?.callerKey === callerKey && frame.windowKey === windowKey) {
        this.#frames.splice(index, 1);
      }
    }
  }

  #pruneFrames(): void {
    const now = this.#now();
    for (let index = this.#frames.length - 1; index >= 0; index -= 1) {
      const expiresAt = this.#frames[index]?.expiresAt;
      if (expiresAt !== undefined && expiresAt <= now) this.#frames.splice(index, 1);
    }
  }

  async #resolveSkyModuleSpecifier(): Promise<string> {
    if (this.#skyModuleSpecifier !== undefined) return this.#skyModuleSpecifier;
    if (this.#options.skyEntryPath !== undefined) {
      const explicit = resolve(this.#options.skyEntryPath);
      await access(explicit);
      this.#skyModuleSpecifier = pathToFileURL(explicit).href;
      return this.#skyModuleSpecifier;
    }
    // The Codex node_repl runtime owns package resolution for its bundled
    // Computer Use package. Avoid enumerating protected WindowsApps paths or
    // binding this daemon to one app-version-specific asset path.
    this.#skyModuleSpecifier = "@oai/sky";
    return this.#skyModuleSpecifier;
  }
}

export const computerUseMethods: ReadonlySet<ComputerUseMethod> = new Set([
  "list_apps",
  "list_windows",
  "get_window",
  "launch_app",
  "get_window_state",
  "click",
  "press_key",
  "type_text",
  "scroll",
  "set_value",
  "drag",
  "perform_secondary_action",
  "activate_window",
]);

const verifiedWindowActionMethods: ReadonlySet<ComputerUseMethod> = new Set([
  "click",
  "press_key",
  "type_text",
  "scroll",
  "set_value",
  "drag",
  "perform_secondary_action",
  "activate_window",
]);

function parseMarker(value: unknown, marker: string): ParsedComputerUseResult {
  for (const text of stringsIn(value)) {
    const index = text.indexOf(marker);
    if (index < 0) continue;
    const encoded = text.slice(index + marker.length).trim();
    let envelope: unknown;
    try {
      envelope = JSON.parse(encoded);
    } catch {
      throw new Error("Computer Use returned a truncated or invalid structured result");
    }
    if (!isObject(envelope) || typeof envelope.ok !== "boolean") {
      throw new Error("Computer Use returned an invalid result envelope");
    }
    if (envelope.ok) {
      return {
        value: envelope.value,
        ...(typeof envelope.helperGeneration === "string"
          ? { helperGeneration: envelope.helperGeneration }
          : {}),
      };
    }
    if (!Object.hasOwn(envelope, "error")) {
      throw new Error("Computer Use returned an invalid error envelope");
    }
    if (!isObject(envelope.error)) {
      const rejected = envelope.error;
      const identity =
        rejected === undefined
          ? "undefined"
          : rejected === null
            ? "null"
            : `${typeof rejected} ${String(rejected)}`;
      throw new ComputerUseNativeResponseError(`Computer Use runtime rejected with ${identity}`);
    }
    const error = envelope.error;
    throw hydrateComputerUseError(error, true);
  }
  throw new Error("Computer Use returned no correlated structured result");
}

function hydrateComputerUseError(value: Record<string, unknown>, nativeResponse = false): Error {
  const name = typeof value.name === "string" ? value.name : "Error";
  const message = typeof value.message === "string" ? value.message : "unknown runtime error";
  const cause = isObject(value.cause) ? hydrateComputerUseError(value.cause) : value.cause;
  const ErrorType = nativeResponse ? ComputerUseNativeResponseError : Error;
  const error = new ErrorType(message, cause === undefined ? undefined : { cause });
  error.name = name;
  if (typeof value.stack === "string") {
    Object.defineProperty(error, "stack", {
      configurable: true,
      enumerable: false,
      writable: true,
      value: value.stack,
    });
  }
  for (const [key, field] of Object.entries(value)) {
    if (["name", "message", "stack", "cause"].includes(key)) continue;
    Object.defineProperty(error, key, {
      configurable: true,
      enumerable: true,
      writable: true,
      value: field,
    });
  }
  return error;
}

function frameRequirement(
  method: ComputerUseMethod,
  args: Record<string, unknown>,
): "none" | "screenshot" | "accessibility" | "state" {
  if (method === "activate_window" || method === "press_key" || method === "type_text") {
    return "none";
  }
  if (method === "scroll" || method === "drag") return "screenshot";
  if (method === "click") {
    return args.element_index === undefined ? "screenshot" : "accessibility";
  }
  if (method === "set_value" || method === "perform_secondary_action") return "accessibility";
  return "state";
}

function requireCallerKey(
  contextThreadId: string | undefined,
  contextTurnId: string | undefined,
  callerSessionId: string | undefined,
): string {
  if (typeof callerSessionId === "string" && callerSessionId.length > 0) {
    return typeof contextThreadId === "string" && contextThreadId.length > 0
      ? `session:${callerSessionId}\u0000thread:${contextThreadId}`
      : `session:${callerSessionId}`;
  }
  if (typeof contextThreadId === "string" && contextThreadId.length > 0) {
    return `thread:${contextThreadId}`;
  }
  if (typeof contextTurnId === "string" && contextTurnId.length > 0) {
    return `turn:${contextTurnId}`;
  }
  throw new Error(
    "Computer Use state-derived operations require a stable caller session, calling thread, or calling turn identity",
  );
}

function requireWindow(value: unknown): ComputerUseWindow {
  if (!isObject(value) || typeof value.app !== "string" || value.app.length === 0) {
    throw new Error("Computer Use window must include a non-empty app identity");
  }
  if (typeof value.id !== "number" || !Number.isFinite(value.id)) {
    throw new Error("Computer Use window must include a finite numeric id");
  }
  if (value.title !== undefined && typeof value.title !== "string") {
    throw new Error("Computer Use window title must be a string when provided");
  }
  return Object.freeze({
    app: value.app,
    id: value.id,
    ...(value.title === undefined ? {} : { title: value.title }),
  });
}

function canonicalWindowKey(window: ComputerUseWindow): string {
  return JSON.stringify([window.app, window.id]);
}

function screenshotGeometry(value: Record<string, unknown>): ScreenshotGeometry | undefined {
  if (typeof value.id !== "string" || value.id.length === 0) return undefined;
  const height = finiteNumber(value.height);
  const originX = finiteNumber(value.originX);
  const originY = finiteNumber(value.originY);
  const width = finiteNumber(value.width);
  const zIndex = finiteNumber(value.zIndex);
  return Object.freeze({
    id: value.id,
    ...(height === undefined ? {} : { height }),
    ...(originX === undefined ? {} : { originX }),
    ...(originY === undefined ? {} : { originY }),
    ...(width === undefined ? {} : { width }),
    ...(zIndex === undefined ? {} : { zIndex }),
  });
}

function finiteNumber(value: unknown): number | undefined {
  return typeof value === "number" && Number.isFinite(value) ? value : undefined;
}

function optionalPositiveInteger(value: number | undefined, field: string): number | undefined {
  if (value === undefined) return undefined;
  if (!Number.isSafeInteger(value) || value <= 0)
    throw new Error(`${field} must be a positive safe integer`);
  return value;
}

function observationExpiry(now: number, ttlMs: number): number {
  const expiresAt = now + ttlMs;
  return Number.isSafeInteger(expiresAt) ? expiresAt : Number.POSITIVE_INFINITY;
}

function stringsIn(value: unknown): string[] {
  if (typeof value === "string") return [value];
  if (Array.isArray(value)) return value.flatMap(stringsIn);
  if (isObject(value)) return Object.values(value).flatMap(stringsIn);
  return [];
}

function jsonLiteral(value: unknown): string {
  const serialized = JSON.stringify(value);
  if (serialized === undefined) throw new Error("Computer Use arguments are not JSON-serializable");
  return serialized;
}

function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}
