import { createHash } from "node:crypto";
import type { Tool } from "@modelcontextprotocol/sdk/types.js";
import { canonicalJson } from "../infrastructure/safety/canonical-json.js";
import { omitBlankOptionalNativeSettingOverrides } from "./native-tool-argument-normalizer.js";
import {
  type AppServerRpcClient,
  type AppServerRpcRequestOptions,
  isModelInvokingAppServerMethod,
} from "./native-tool-catalog.js";
import type { NativeToolStateEffect } from "./native-tool-registry.js";

export type JsonSchema = boolean | Record<string, unknown>;

export interface AppServerSchemaSource {
  loadClientRequestSchema(): Promise<Record<string, unknown>>;
}

export interface AppServerMethodDescriptor {
  readonly exposedName: string;
  readonly method: string;
  readonly invokesModel: boolean;
  readonly stateEffect: NativeToolStateEffect;
  readonly requestTitle: string | undefined;
  /**
   * App Server requests whose generated protocol schema models an absent
   * `params` member as singleton `null` cannot be exposed directly as an MCP
   * or Dynamic Tool input schema.  The public tool accepts an exact empty
   * object and this flag restores the original wire representation.
   */
  readonly requestParamsMode?: "omit" | "null";
  readonly tool: Tool;
}

export interface AppServerMethodCatalogSnapshot {
  readonly refreshedAtUnixMs: number;
  readonly methods: readonly AppServerMethodDescriptor[];
  readonly schemaDigest: string;
}

export interface AppServerMethodCatalogOptions {
  readonly reservedNames?: readonly string[];
}

export interface AppServerCatalogIncompatibilityDetails {
  readonly source: "codex_app_server_schema";
  readonly variant: "root" | "oneOf" | "anyOf" | "direct";
  readonly index?: number;
  readonly location: string;
  readonly variantIndex?: number;
  readonly rawShape: unknown;
}

/** The installed App Server advertised a request shape that cannot be called losslessly. */
export class AppServerCatalogIncompatibilityError extends Error {
  readonly code = "APP_SERVER_CATALOG_INCOMPATIBLE";
  readonly details: AppServerCatalogIncompatibilityDetails;

  constructor(reason: string, details: AppServerCatalogIncompatibilityDetails) {
    super(`${reason} at ${details.location}`);
    this.name = "AppServerCatalogIncompatibilityError";
    this.details = details;
  }
}

/**
 * Converts the protocol schema generated by the installed Codex binary into
 * first-class MCP tools. No checked-in method census is treated as complete.
 */
export class AppServerMethodCatalog {
  readonly #source: AppServerSchemaSource;
  readonly #reservedNames: ReadonlySet<string>;
  #snapshot: AppServerMethodCatalogSnapshot = {
    refreshedAtUnixMs: 0,
    methods: [],
    schemaDigest: "",
  };

  constructor(source: AppServerSchemaSource, options: AppServerMethodCatalogOptions = {}) {
    this.#source = source;
    this.#reservedNames = new Set(options.reservedNames ?? []);
  }

  get snapshot(): AppServerMethodCatalogSnapshot {
    return this.#snapshot;
  }

  async prepareRefresh(): Promise<AppServerMethodCatalogSnapshot> {
    const schema = await this.#source.loadClientRequestSchema();
    const next = parseAppServerMethodCatalog(schema, this.#reservedNames);
    return {
      ...next,
      refreshedAtUnixMs: Date.now(),
    };
  }

  commitRefresh(snapshot: AppServerMethodCatalogSnapshot): void {
    this.#snapshot = snapshot;
  }

  async refresh(): Promise<AppServerMethodCatalogSnapshot> {
    const snapshot = await this.prepareRefresh();
    this.commitRefresh(snapshot);
    return snapshot;
  }
}

export class AppServerMethodExecutor {
  readonly #client: AppServerRpcClient;

  constructor(client: AppServerRpcClient) {
    this.#client = client;
  }

  async call(
    descriptor: AppServerMethodDescriptor,
    argumentsValue: unknown,
    timeoutOrOptions?: number | AppServerRpcRequestOptions,
  ): Promise<unknown> {
    const wireArguments = appServerWireArguments(descriptor, argumentsValue);
    if (timeoutOrOptions === undefined) {
      return this.#client.request(descriptor.method, wireArguments);
    }
    const options =
      typeof timeoutOrOptions === "number"
        ? { timeoutMs: timeoutOrOptions }
        : { ...timeoutOrOptions };
    return this.#client.request(descriptor.method, wireArguments, {
      ...options,
      ...(descriptor.stateEffect === "mutate" ? { awaitResponseAfterCancellation: true } : {}),
    });
  }
}

export function parseAppServerMethodCatalog(
  schema: Record<string, unknown>,
  reservedNames: ReadonlySet<string> = new Set(),
): Omit<AppServerMethodCatalogSnapshot, "refreshedAtUnixMs"> {
  const definitions = isObject(schema.definitions) ? schema.definitions : {};
  const dollarDefinitions = isObject(schema.$defs) ? schema.$defs : {};
  const root = resolveSchemaObject(schema, schema, "schema");
  const variants = requestVariants(root, schema);
  const candidates: ParsedAppServerMethod[] = [];

  for (const [variantIndex, rawVariant] of variants.values.entries()) {
    const location =
      variants.keyword === "direct"
        ? "schema"
        : `schema.${variants.keyword}[${String(variantIndex)}]`;
    const variant = resolveSchemaObject(rawVariant, schema, location, variantIndex);
    if (!isObject(variant.properties)) {
      throw appServerIncompatibility(
        "App Server request variant has no object properties",
        `${location}.properties`,
        variant.properties,
        variantIndex,
      );
    }
    const rawMethodSchema = variant.properties.method;
    const methodSchema = resolveSchemaObject(
      rawMethodSchema,
      schema,
      `${location}.properties.method`,
      variantIndex,
    );
    const methods = requestMethodNames(methodSchema, `${location}.properties.method`, variantIndex);
    const protocolParamsSchema = bundleParamsSchema(
      variant.properties.params,
      definitions,
      dollarDefinitions,
      `${location}.properties.params`,
      variantIndex,
    );
    const paramsRequired =
      Array.isArray(variant.required) && variant.required.some((name) => name === "params");
    const paramsContract = appServerToolParamsContract(protocolParamsSchema, paramsRequired);
    const requestTitle = typeof variant.title === "string" ? variant.title : undefined;
    const nativeDescription =
      typeof variant.description === "string" ? variant.description : undefined;
    for (const method of methods) {
      candidates.push({
        method,
        paramsSchema: paramsContract.inputSchema,
        ...(paramsContract.requestParamsMode === undefined
          ? {}
          : { requestParamsMode: paramsContract.requestParamsMode }),
        ...(paramsContract.originalInputSchema === undefined
          ? {}
          : { originalInputSchema: paramsContract.originalInputSchema }),
        requestTitle: requestTitle ?? appServerMethodFallbackTitle(method),
        description: nativeDescription ?? appServerMethodFallbackDescription(method),
        ...(isObject(variant.annotations)
          ? { annotations: variant.annotations as NonNullable<Tool["annotations"]> }
          : {}),
        ...(isObject(variant._meta) ? { metadata: variant._meta } : {}),
      });
    }
  }

  candidates.sort(compareParsedMethods);
  const exposedNames = allocateAppServerToolNames(candidates, reservedNames);
  const descriptors = candidates.map((candidate, index): AppServerMethodDescriptor => {
    const exposedName = exposedNames[index];
    if (exposedName === undefined) throw new Error("App Server tool name allocation failed");
    const invokesModel = isModelInvokingAppServerMethod(candidate.method);
    const stateEffect = classifyAppServerStateEffect(candidate.method);
    const tool = {
      name: exposedName,
      ...(candidate.requestTitle === undefined ? {} : { title: candidate.requestTitle }),
      ...(candidate.description === undefined ? {} : { description: candidate.description }),
      inputSchema: candidate.paramsSchema,
      ...(candidate.annotations === undefined ? {} : { annotations: candidate.annotations }),
      _meta: {
        ...candidate.metadata,
        omnicodex: {
          ...(isObject(candidate.metadata?.omnicodex) ? candidate.metadata.omnicodex : {}),
          source: "codex_app_server_schema",
          originalName: candidate.method,
          exposedName,
          invokesModel,
          ...(candidate.requestParamsMode === undefined
            ? {}
            : {
                requestParamsMode: candidate.requestParamsMode,
                originalInputSchema: candidate.originalInputSchema,
              }),
        },
      },
    } as unknown as Tool;
    return {
      exposedName,
      method: candidate.method,
      invokesModel,
      stateEffect,
      requestTitle: candidate.requestTitle,
      ...(candidate.requestParamsMode === undefined
        ? {}
        : { requestParamsMode: candidate.requestParamsMode }),
      tool,
    };
  });
  const schemaDigest = createHash("sha256").update(JSON.stringify(schema), "utf8").digest("hex");
  return { methods: descriptors, schemaDigest };
}

function appServerMethodFallbackTitle(method: string): string | undefined {
  switch (method) {
    case "fs/readFile":
      return "Read a file";
    case "fs/writeFile":
      return "Write a file";
    case "fs/getMetadata":
      return "Read file details";
    case "command/exec":
      return "Run a program";
    default:
      return undefined;
  }
}

function appServerMethodFallbackDescription(method: string): string | undefined {
  switch (method) {
    case "fs/readFile":
      return "Reads the file at the supplied absolute path and returns its contents.";
    case "fs/writeFile":
      return "Writes the supplied base64 file contents to the supplied absolute path and returns the completed filesystem result.";
    case "fs/getMetadata":
      return "Returns filesystem details for the supplied absolute path.";
    case "command/exec":
      return DIRECT_WINDOWS_COMMAND_EXECUTION_DESCRIPTION;
    case "thread/start":
      return "Start a native Codex thread with the exact advertised settings. Omit model and modelProvider to inherit the configured defaults; blank string overrides are removed rather than submitted as unsupported model names.";
    case "thread/resume":
      return "Resume the exact native Codex thread without creating a replacement. Omit model and modelProvider to inherit its configured settings; blank string overrides are removed rather than submitted as unsupported model names.";
    case "turn/start":
      return "Start one native turn on the selected Codex thread. Omit model and modelProvider to inherit the thread settings; blank string overrides are removed rather than submitted as unsupported model names.";
    case "turn/settings/update":
      return "Update only the explicitly supplied native turn settings. Omit model and modelProvider to preserve the current values; blank string overrides are removed.";
    default:
      return undefined;
  }
}

const DIRECT_WINDOWS_COMMAND_EXECUTION_DESCRIPTION =
  "Runs the executable in command[0] with the remaining command values as separate arguments and returns stdout, stderr, exit status, and process information. For PowerShell syntax, use powershell.exe with -Command; for cmd syntax, use cmd.exe with /c followed by the complete command. Optional working directory, environment, terminal, streaming, timeout, output, and execution settings follow the published input schema.";

interface ParsedAppServerMethod {
  readonly method: string;
  readonly paramsSchema: JsonSchema;
  readonly requestParamsMode?: "omit" | "null";
  readonly originalInputSchema?: JsonSchema;
  readonly requestTitle: string | undefined;
  readonly description: string | undefined;
  readonly annotations?: NonNullable<Tool["annotations"]>;
  readonly metadata?: Record<string, unknown>;
}

interface AppServerToolParamsContract {
  readonly inputSchema: JsonSchema;
  readonly requestParamsMode?: "omit" | "null";
  readonly originalInputSchema?: JsonSchema;
}

function appServerToolParamsContract(
  protocolSchema: JsonSchema,
  paramsRequired: boolean,
): AppServerToolParamsContract {
  if (!isSingletonNullSchema(protocolSchema)) {
    return { inputSchema: protocolSchema };
  }
  return {
    inputSchema: { type: "object", properties: {}, additionalProperties: false },
    requestParamsMode: paramsRequired ? "null" : "omit",
    originalInputSchema: protocolSchema,
  };
}

function isSingletonNullSchema(schema: JsonSchema): boolean {
  if (typeof schema === "boolean") return false;
  if (schema.type === "null") return true;
  return schema.const === null && !Object.hasOwn(schema, "type");
}

function appServerWireArguments(
  descriptor: AppServerMethodDescriptor,
  argumentsValue: unknown,
): unknown {
  if (descriptor.requestParamsMode === undefined) {
    return omitBlankOptionalModelOverrides(descriptor, argumentsValue);
  }
  if (
    argumentsValue !== undefined &&
    argumentsValue !== null &&
    (!isObject(argumentsValue) || Object.keys(argumentsValue).length !== 0)
  ) {
    throw new TypeError(`${descriptor.exposedName} does not accept arguments`);
  }
  return descriptor.requestParamsMode === "null" ? null : undefined;
}

function omitBlankOptionalModelOverrides(
  descriptor: AppServerMethodDescriptor,
  argumentsValue: unknown,
): unknown {
  return omitBlankOptionalNativeSettingOverrides(descriptor.tool.inputSchema, argumentsValue);
}

function requestMethodNames(
  methodSchema: Record<string, unknown>,
  location: string,
  variantIndex: number,
): string[] {
  if (typeof methodSchema.const === "string" && methodSchema.const.length > 0) {
    return [methodSchema.const];
  }
  if (methodSchema.const !== undefined) {
    throw appServerIncompatibility(
      "App Server request method const is not a non-empty string",
      `${location}.const`,
      methodSchema.const,
      variantIndex,
    );
  }
  if (!Array.isArray(methodSchema.enum) || methodSchema.enum.length === 0) {
    throw appServerIncompatibility(
      "App Server request method has no callable const or enum",
      location,
      methodSchema,
      variantIndex,
    );
  }
  const methods = methodSchema.enum;
  if (methods.some((candidate) => typeof candidate !== "string" || candidate.length === 0)) {
    throw appServerIncompatibility(
      "App Server request method enum contains a non-callable value",
      `${location}.enum`,
      methods,
      variantIndex,
    );
  }
  return [...new Set(methods as string[])];
}

function bundleParamsSchema(
  rawParamsSchema: unknown,
  definitions: Record<string, unknown>,
  dollarDefinitions: Record<string, unknown>,
  location: string,
  variantIndex: number,
): JsonSchema {
  const root = cloneSchema(rawParamsSchema);
  if (typeof root === "boolean") {
    return root;
  }
  if (!isObject(root)) {
    return { type: "object", additionalProperties: true };
  }
  const referencedNames = new Set<string>();
  const referencedDollarNames = new Set<string>();
  const localRoot = root;
  collectDefinitionRefs(
    root,
    localRoot,
    definitions,
    dollarDefinitions,
    referencedNames,
    referencedDollarNames,
    location,
    variantIndex,
  );
  const bundledDefinitions: Record<string, unknown> = {};
  for (const name of [...referencedNames].sort((left, right) => left.localeCompare(right, "en"))) {
    const definition = definitions[name];
    if (definition !== undefined) {
      bundledDefinitions[name] = cloneSchema(definition);
    }
  }
  const bundledDollarDefinitions: Record<string, unknown> = {};
  for (const name of [...referencedDollarNames].sort((left, right) =>
    left.localeCompare(right, "en"),
  )) {
    const definition = dollarDefinitions[name];
    if (definition !== undefined) {
      bundledDollarDefinitions[name] = cloneSchema(definition);
    }
  }
  return {
    ...root,
    ...(Object.keys(bundledDefinitions).length === 0
      ? {}
      : {
          definitions: {
            ...(isObject(root.definitions) ? root.definitions : {}),
            ...bundledDefinitions,
          },
        }),
    ...(Object.keys(bundledDollarDefinitions).length === 0
      ? {}
      : {
          $defs: {
            ...(isObject(root.$defs) ? root.$defs : {}),
            ...bundledDollarDefinitions,
          },
        }),
  };
}

function collectDefinitionRefs(
  value: unknown,
  localRoot: Record<string, unknown>,
  definitions: Record<string, unknown>,
  dollarDefinitions: Record<string, unknown>,
  names: Set<string>,
  dollarNames: Set<string>,
  location: string,
  variantIndex: number,
): void {
  if (Array.isArray(value)) {
    for (const [index, item] of value.entries()) {
      collectDefinitionRefs(
        item,
        localRoot,
        definitions,
        dollarDefinitions,
        names,
        dollarNames,
        `${location}[${String(index)}]`,
        variantIndex,
      );
    }
    return;
  }
  if (!isObject(value)) {
    return;
  }
  const reference = value.$ref;
  if (reference !== undefined) {
    if (typeof reference !== "string" || reference.length === 0) {
      throw appServerIncompatibility(
        "App Server params schema reference is not a non-empty string",
        `${location}.$ref`,
        reference,
        variantIndex,
      );
    }
    if (reference.startsWith("#/definitions/")) {
      collectBundledDefinition(
        reference,
        "#/definitions/",
        localRoot,
        definitions,
        dollarDefinitions,
        names,
        dollarNames,
        location,
        variantIndex,
      );
    } else if (reference.startsWith("#/$defs/")) {
      collectBundledDefinition(
        reference,
        "#/$defs/",
        localRoot,
        dollarDefinitions,
        definitions,
        dollarNames,
        names,
        location,
        variantIndex,
      );
    } else if (!hasLocalSchemaReference(localRoot, reference)) {
      throw appServerIncompatibility(
        "App Server params schema reference cannot be represented in the standalone tool schema",
        `${location}.$ref`,
        reference,
        variantIndex,
      );
    }
  }
  for (const [key, nested] of Object.entries(value)) {
    collectDefinitionRefs(
      nested,
      localRoot,
      definitions,
      dollarDefinitions,
      names,
      dollarNames,
      `${location}.${key}`,
      variantIndex,
    );
  }
}

function hasLocalSchemaReference(root: Record<string, unknown>, reference: string): boolean {
  if (reference === "#") return true;
  if (reference.startsWith("#/")) return localReferenceTarget(root, reference) !== undefined;
  if (!reference.startsWith("#") || reference.length === 1) return false;
  let anchor: string;
  try {
    anchor = decodeURIComponent(reference.slice(1));
  } catch {
    return false;
  }
  return containsSchemaAnchor(root, anchor);
}

function containsSchemaAnchor(
  value: unknown,
  anchor: string,
  seen = new WeakSet<object>(),
): boolean {
  if (Array.isArray(value)) {
    if (seen.has(value)) return false;
    seen.add(value);
    return value.some((entry) => containsSchemaAnchor(entry, anchor, seen));
  }
  if (!isObject(value)) return false;
  if (seen.has(value)) return false;
  seen.add(value);
  if (value.$anchor === anchor || value.$dynamicAnchor === anchor) return true;
  return Object.values(value).some((entry) => containsSchemaAnchor(entry, anchor, seen));
}

function collectBundledDefinition(
  reference: string,
  prefix: "#/definitions/" | "#/$defs/",
  localRoot: Record<string, unknown>,
  sourceDefinitions: Record<string, unknown>,
  otherDefinitions: Record<string, unknown>,
  names: Set<string>,
  otherNames: Set<string>,
  location: string,
  variantIndex: number,
): void {
  if (localReferenceTarget(localRoot, reference) !== undefined) return;
  const name = firstReferenceSegment(reference.slice(prefix.length));
  if (name === undefined || !Object.hasOwn(sourceDefinitions, name)) {
    throw appServerIncompatibility(
      "App Server params schema reference does not resolve",
      `${location}.$ref`,
      reference,
      variantIndex,
    );
  }
  if (names.has(name)) return;
  names.add(name);
  collectDefinitionRefs(
    sourceDefinitions[name],
    localRoot,
    prefix === "#/definitions/" ? sourceDefinitions : otherDefinitions,
    prefix === "#/$defs/" ? sourceDefinitions : otherDefinitions,
    prefix === "#/definitions/" ? names : otherNames,
    prefix === "#/$defs/" ? names : otherNames,
    `${prefix === "#/definitions/" ? "schema.definitions" : "schema.$defs"}.${name}`,
    variantIndex,
  );
}

function firstReferenceSegment(value: string): string | undefined {
  const rawSegment = value.split("/", 1)[0];
  if (rawSegment === undefined || rawSegment.length === 0) return undefined;
  try {
    return decodeURIComponent(rawSegment).replaceAll("~1", "/").replaceAll("~0", "~");
  } catch {
    return undefined;
  }
}

export function classifyAppServerStateEffect(method: string): NativeToolStateEffect {
  return /(?:^|\/)(?:get|list|read|status|search|find|inspect|load|wait)(?:$|[A-Z_/-])/u.test(
    method,
  )
    ? "read"
    : "mutate";
}

function appServerToolBaseName(method: string): string {
  const sanitized = method.replace(/[^A-Za-z0-9_.-]+/g, "_") || "unknown";
  const base = `codex__app_server__${sanitized}`;
  if (base.length <= 128) {
    return base;
  }
  return appServerToolNameWithSuffix(base, method);
}

function allocateAppServerToolNames(
  candidates: readonly ParsedAppServerMethod[],
  reservedNames: ReadonlySet<string>,
): string[] {
  const bases = candidates.map(({ method }) => appServerToolBaseName(method));
  const baseCounts = new Map<string, number>();
  for (const base of bases) baseCounts.set(base, (baseCounts.get(base) ?? 0) + 1);
  const used = new Set<string>();
  return candidates.map((candidate, index) => {
    const base = bases[index] ?? "codex__app_server__unknown";
    if (baseCounts.get(base) === 1 && !reservedNames.has(base) && !used.has(base)) {
      used.add(base);
      return base;
    }
    const identity = appServerMethodIdentity(candidate);
    for (let ordinal = 1n; ; ordinal += 1n) {
      const name = appServerToolNameWithSuffix(base, `${identity}\n${ordinal.toString(10)}`);
      if (!reservedNames.has(name) && !used.has(name)) {
        used.add(name);
        return name;
      }
    }
  });
}

function appServerToolNameWithSuffix(base: string, identity: string): string {
  const digest = createHash("sha256").update(identity, "utf8").digest("hex");
  return `${base.slice(0, 62)}__${digest}`;
}

function appServerMethodIdentity(candidate: ParsedAppServerMethod): string {
  return canonicalJson({
    method: candidate.method,
    paramsSchema: candidate.paramsSchema,
    requestTitle: candidate.requestTitle,
    description: candidate.description,
  });
}

function compareParsedMethods(left: ParsedAppServerMethod, right: ParsedAppServerMethod): number {
  return (
    left.method.localeCompare(right.method, "en") ||
    appServerMethodIdentity(left).localeCompare(appServerMethodIdentity(right), "en")
  );
}

function requestVariants(
  root: Record<string, unknown>,
  schema: Record<string, unknown>,
): { readonly keyword: "oneOf" | "anyOf" | "direct"; readonly values: readonly unknown[] } {
  const oneOf = root.oneOf;
  if (Array.isArray(oneOf) && oneOf.length > 0) {
    return { keyword: "oneOf", values: oneOf };
  }
  if (oneOf !== undefined) {
    throw appServerIncompatibility(
      "App Server request oneOf is not a non-empty array",
      "schema.oneOf",
      oneOf,
    );
  }
  const anyOf = root.anyOf;
  if (Array.isArray(anyOf) && anyOf.length > 0) {
    return { keyword: "anyOf", values: anyOf };
  }
  if (anyOf !== undefined) {
    throw appServerIncompatibility(
      "App Server request anyOf is not a non-empty array",
      "schema.anyOf",
      anyOf,
    );
  }
  if (isObject(root.properties) && root.properties.method !== undefined) {
    return { keyword: "direct", values: [root] };
  }
  throw appServerIncompatibility(
    "App Server request schema has no callable union or direct method",
    "schema",
    schema,
  );
}

function resolveSchemaObject(
  value: unknown,
  schema: Record<string, unknown>,
  location: string,
  variantIndex?: number,
): Record<string, unknown> {
  if (!isObject(value)) {
    throw appServerIncompatibility(
      "App Server schema node is not an object",
      location,
      value,
      variantIndex,
    );
  }
  let current = value;
  const seen = new Set<string>();
  while (typeof current.$ref === "string") {
    const reference = current.$ref;
    if (!reference.startsWith("#/")) {
      throw appServerIncompatibility(
        "App Server schema uses an unsupported non-local reference",
        `${location}.$ref`,
        reference,
        variantIndex,
      );
    }
    if (seen.has(reference)) {
      throw appServerIncompatibility(
        "App Server schema reference cycle cannot be flattened",
        `${location}.$ref`,
        reference,
        variantIndex,
      );
    }
    seen.add(reference);
    const target = localReferenceTarget(schema, reference);
    if (!isObject(target)) {
      throw appServerIncompatibility(
        "App Server schema reference does not resolve to an object",
        `${location}.$ref`,
        reference,
        variantIndex,
      );
    }
    const { $ref: _reference, ...siblings } = current;
    current = { ...target, ...siblings };
  }
  return current;
}

function localReferenceTarget(schema: Record<string, unknown>, reference: string): unknown {
  let current: unknown = schema;
  for (const rawSegment of reference.slice(2).split("/")) {
    let segment: string;
    try {
      segment = decodeURIComponent(rawSegment).replaceAll("~1", "/").replaceAll("~0", "~");
    } catch {
      return undefined;
    }
    if (!isObject(current) || !Object.hasOwn(current, segment)) return undefined;
    current = current[segment];
  }
  return current;
}

function appServerIncompatibility(
  reason: string,
  location: string,
  value: unknown,
  variantIndex?: number,
): AppServerCatalogIncompatibilityError {
  return new AppServerCatalogIncompatibilityError(reason, {
    source: "codex_app_server_schema",
    variant: appServerVariant(location, variantIndex),
    ...(variantIndex === undefined ? {} : { index: variantIndex }),
    location,
    ...(variantIndex === undefined ? {} : { variantIndex }),
    rawShape: rawShape(value),
  });
}

function appServerVariant(
  location: string,
  variantIndex: number | undefined,
): AppServerCatalogIncompatibilityDetails["variant"] {
  if (location.includes(".oneOf[")) return "oneOf";
  if (location.includes(".anyOf[")) return "anyOf";
  return variantIndex === undefined ? "root" : "direct";
}

function rawShape(value: unknown, seen = new WeakSet<object>()): unknown {
  if (value === null) return { kind: "null" };
  if (Array.isArray(value)) {
    if (seen.has(value)) return { kind: "array", circular: true };
    seen.add(value);
    return {
      kind: "array",
      length: value.length,
      items: value.map((item) => rawShape(item, seen)),
    };
  }
  if (isObject(value)) {
    if (seen.has(value)) return { kind: "object", circular: true };
    seen.add(value);
    return {
      kind: "object",
      fields: Object.fromEntries(
        Object.keys(value)
          .sort((left, right) => left.localeCompare(right, "en"))
          .map((key) => [key, rawShape(value[key], seen)]),
      ),
    };
  }
  return { kind: typeof value };
}

function cloneSchema<T>(value: T): T {
  if (value === undefined) {
    return value;
  }
  return structuredClone(value);
}

function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}
